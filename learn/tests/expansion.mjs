if(await page.locator('[data-batch]').count()!==4)throw Error('Expected 4 quiz batches');
await page.locator('[data-batch="3"]').click();
if(await page.locator('section[id^="task-"]').count()!==10)throw Error('Missing questions in batch 4');
await page.getByRole('button',{name:'05 Mock exams'}).click();
await page.locator('[data-start="sprint-data"]').click();
if(await page.locator('.exam-question').count()!==3)throw Error('Sprint must show 3 questions');
await page.getByRole('button',{name:'Submit all answers'}).click();
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'03 Practice desk'}).click();
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
await page.screenshot({path:'/private/tmp/learn-expansion-mobile.png',fullPage:true});
if(errors.length)throw Error(errors.join('\n'));
console.log('Practice navigation, worked examples, executable grading, all quiz batches, sprint submission, mobile layout: PASS');
