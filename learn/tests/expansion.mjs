import {chromium} from '../../savetheworld/node_modules/playwright/index.mjs';
import {lessons,quiz,diagnostic,exams} from '../content.mjs';
const tasks=[...diagnostic,...lessons.flatMap(l=>l.drills),...quiz,...exams.flatMap(e=>e.tasks)];
if(new Set(tasks.map(q=>q.id)).size!==tasks.length)throw Error('Task IDs must be unique');
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.LEARN_URL||'http://127.0.0.1:8098/learn/');
const practice=lessons.filter(l=>l.practice);
const checks=practice.flatMap(l=>l.drills).filter(q=>q.type==='code');
