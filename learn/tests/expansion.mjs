const failures=await page.evaluate(async tasks=>{const w=new Worker('./worker.mjs',{type:'module'});const bad=[];for(const q of tasks){const r=await new Promise(resolve=>{w.onmessage=({data})=>{if(data.done)resolve(data)};w.postMessage({setup:q.setup,code:q.solution,reference:q.reference,checks:q.checks})});if(r.error||!r.checks?.every(Boolean))bad.push({id:q.id,...r});}w.terminate();return bad;},checks);
if(failures.length)throw Error(JSON.stringify(failures));
console.log(`${checks.length} new coding solutions and worked examples passed`);
await page.getByRole('button',{name:'03 Practice desk'}).click();
await page.locator('[data-lesson="practice-retail"]').first().click();
await page.getByText('Worked example 1 · Currency strings: invalid is not zero',{exact:true}).click();
await page.locator('[data-drill="3"]').click();
await page.locator('#answer-r4').fill(practice.find(l=>l.id==='practice-retail').drills[3].solution);
await page.locator('[data-run="r4"]').click();
await page.waitForFunction(()=>document.querySelector('#output-r4')?.textContent.includes('8/8'),{},{timeout:90000});
